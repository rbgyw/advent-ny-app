export type SportLevel = keyof typeof sportLevels;

export const teamPoses = ['03', '01', '02', '04'] as const;
export type TeamPose = (typeof teamPoses)[number];

export function isTeamPose(value: unknown): value is TeamPose {
  return teamPoses.some(pose => pose === value);
}

export interface SportSubmission {
  attachmentId: string;
  teamPose?: TeamPose;
}

export function isSportLevel(value: unknown): value is SportLevel {
  return typeof value === 'string' && Object.hasOwn(sportLevels, value);
}
